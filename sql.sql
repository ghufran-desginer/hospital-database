Create table DEPARTMENT(
DEPT_ID number(6) primary key ,
DEPT_NAME Varchar2(100) not null unique ,
CITY varchar2(100) ,
STREET varchar2(100) ,
MGR_ID number(6)
);



CREATE table EMPLOYEE(
EMP_ID     number(6)  constraint PK_EMPLOYEE  primary key,
FIRST_NAME varchar2(30) not null,
LAST_NAME  varchar2(30) not null,
PHONE      varchar2(15),
SALARY     number(8,2),
DEPT_ID    number(6) not null,
constraint FK_EMP_DEPT foreign key(DEPT_ID)
references DEPARTMENT(DEPT_ID)
);

alter table DEPARTMENT 
ADD constraint FK_DEPT_MGR foreign key 
(MGR_ID) references EMPLOYEE(EMP_ID);


CREATE table STAFF(
EMP_ID number(6) constraint PK_STAFF primary key,
JOB_TITLE varchar2(50) not null ,
constraint FK_STAFF_EMP foreign key
(EMP_ID) references EMPLOYEE(EMP_ID) on 
delete cascade
);


create table DOCTOR(
EMP_ID number(6) primary key ,
SPECIALIZATION varchar2(100),
LICENSE_NO varchar2(50),
constraint FK_DOC_EMP foreign key (EMP_ID) references EMPLOYEE(EMP_ID) on delete cascade
);

create table ROOM(
ROOM_NO number(8)primary key ,
  Type varchar2(20) ,
DAILY_RATE decimal(10,2) not null
);


 create table PATIENT(
 PATIENT_ID    number(6) primary key ,
 FIRST_NAME  varchar2(30) not null ,
 MIDDLE_NAME  varchar2(30)  ,
  LAST_NAME  varchar2(30) not null ,
 BIRTH_DATE    date,
GENDER        char(1),
PHONE        varchar2(9),
ROOM_NO      number(8),
MEDICAL_ID number(10),
 foreign key (ROOM_NO) REFERENCES ROOM (ROOM_NO) on delete set null 
 );



create table TREATED_BY(
DOC_ID number(6),
PAT_ID number(6),
TREATMENT_DATE date,
constraint PK_TREATED_BY primary key 
(DOC_ID,PAT_ID,TREATMENT_DATE),
constraint FK_TB_DOC foreign key
(DOC_ID) references DOCTOR(EMP_ID),
constraint FK_TB_PAT foreign key
(PAT_ID) references PATIENT(PATIENT_ID)
);





CREATE table APPOINTMENT(
APP_ID     number(10) constraint PK_APPOINTMENT primary key,
APP_DATE   date not null,
APP_TIME  varchar2(10),
STATUS     varchar2(20) default 'Scheduled' check (STATUS in 
('Scheduled' , 'Completed' , 'Cancelled')),
PATIENT_ID number(6) not null,
DOCTOR_ID  number(6) not null,
constraint FK_APP_PATIENT foreign key (PATIENT_ID) references
PATIENT(PATIENT_ID),
constraint  FK_APP_DOCTOR foreign key
(DOCTOR_ID) references DOCTOR(EMP_ID)
);




CREATE table INVOICE(
INVOICE_ID      number(10) constraint
PK_INVOICE      primary key,
ISSUE_DATE      date default sysdate,
TOTAL_AMOUNT    number(8,2) not null,
PAYMENT_STATUS  varchar2(20) default
'Unpaid'  check(PAYMENT_STATUS in
('Paid','Unpaid','Pending')),
PATIENT_ID      NUMBER(6) NOT NULL,
constraint FK_INV_PATIENT
foreign key (PATIENT_ID) references
PATIENT(PATIENT_ID)
);


CREATE table MEDICAL_RECORD(
RECORD_ID     number(10) constraint 
PK_MED_RECORD primary  key,
RECORD_DATE   date default sysdate,
DIAGNOSIS     varchar2(255) not null,
PRESCRIPTION  varchar2(255),
PATIENT_ID    number(6) not null,
DOCTOR_ID     number(6) not null,
constraint FK_REC_DOCTOR foreign key(DOCTOR_ID)
references DOCTOR (EMP_ID),
constraint FK_REC_PATIENT foreign key(PATIENT_ID)
references PATIENT (PATIENT_ID)
);



 

create table SURGERY(
SURGERY_ID number(6) primary key,
DOCTOR_ID NUMBER(6) not null,
PATIENT_ID number(6) not null,
SURGERY_NAME varchar2(50) not null,
SURGERY_DATE DATE,
OPERATION_RM varchar2(20),
STATUS varchar2(20),
constraint SURG_PAT foreign key (PATIENT_ID) references PATIENT(PATIENT_ID) on delete cascade,
constraint SURG_DOC foreign key (DOCTOR_ID) REFERENCES DOCTOR(EMP_ID)
);



CREATE table MEDICATION(
MED_ID number(6) primary key,
MED_NAME varchar2(100) not null,
DOSAGE varchar2(20),
FREQUENCY varchAR2(50),
START_DATE DATE ,
END_DATE DATE,
PAT_ID number(6) not null,
DOCTOR_ID number(6) not null,
constraint FK_MED_DOC foreign key (DOCTOR_ID) references DOCTOR (EMP_ID) on delete cascade,
constraint FK_MED_PAT FOREIGN KEY (PAT_ID) references PATIENT(PATIENT_ID) on delete cascade
);


CREATE TABLE DEPENDENT(
EMPLOYEE_ID number(6) ,
P_NAME VARCHAR2(20) ,
SEX CHAR(1) ,
BIRTH_DATE DATE,
RELATIONSHIP VARCHAR2(30) NOT NULL,
 constraint PK_DEPENDENT primary key (EMPLOYEE_ID,P_NAME),
 CONSTRAINT FK_DEP_EMP foreign key (EMPLOYEE_ID) references EMPLOYEE(EMP_ID)
 on delete cascade
);








