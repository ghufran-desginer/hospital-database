emp.first_name||''||emp.last_name as doctor_name ,
doc.specialization
FROM PATIENT P join APPOINTMENT ap on P.PATIENT_ID=ap.PATIENT_ID
join doctor doc on ap.doctor_id=doc.emp_id
join employee emp on doc.emp_id=emp.emp_id
;



